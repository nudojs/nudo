// ─── table helpers ───────────────────────────────────────────────────────────

const escCell = (s) => {
  // MDX treats bare `{…}` as expressions and `<…>` as JSX. Keep inline `code`
  // spans intact; HTML-escape those metacharacters everywhere else.
  const raw = String(s ?? "").replaceAll("|", "\\|").replaceAll("\n", " ").trim();
  const parts = raw.split(/(`[^`]*`)/g);
  return parts
    .map((p) => (p.startsWith("`") && p.endsWith("`") && p.length > 1
      ? p
      : p
          .replaceAll("&", "&amp;")
          .replaceAll("{", "&#123;")
          .replaceAll("}", "&#125;")
          .replaceAll("<", "&lt;")
          .replaceAll(">", "&gt;")))
    .join("");
};

const dash = "—";

function tableRow(cells) {
  return `| ${cells.map(escCell).join(" | ")} |`;
}

function symbolTable(lang, rows) {
  const head =
    lang === "zh"
      ? ["名称", "种类", "说明", "签名"]
      : ["Name", "Kind", "Summary", "Signature"];
  const lines = [
    tableRow(head),
    `|${head.map(() => "------").join("|")}|`,
    ...rows.map((r) =>
      tableRow([`\`${r.name}\``, r.kind, r.summary || dash, r.signature ? `\`${r.signature}\`` : dash]),
    ),
  ];
  return lines.join("\n");
}

