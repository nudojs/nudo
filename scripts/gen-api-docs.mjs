/** Extract backticked symbol names from a PUBLIC_API cell (`litC()` → `litC`). */
function symbolsInCell(cell) {
  const names = [];
  for (const m of cell.matchAll(/`([^`]+)`/g)) {
    const raw = m[1].trim();
    const name = raw.replace(/\(.*$/, "").trim();
    if (!name || name === "…" || name.includes(" ") || name.includes("/")) continue;
    if (!/^[\w$]+$/.test(name)) continue;
    names.push(name);
  }
  return names;
}

function parseCorePublicApi() {
  const md = read("packages/core/PUBLIC_API.md");
  const start = md.indexOf("## 2. Entry points");
  const stop = md.indexOf("## 3. Internal");
  if (start === -1 || stop === -1) throw new Error("core PUBLIC_API.md §2 not found");
  const section = md.slice(start, stop);

  const rows = new Map();
  // | Symbol | Kind | Role | Stability |  and  | Symbol family | Role | Stability |
  for (const line of section.split("\n")) {
    if (!line.trim().startsWith("|")) continue;
    const cells = line.split("|").slice(1, -1).map((c) => c.trim());
    if (cells.length < 3) continue;
    if (/^[-:]+$/.test(cells[0].replaceAll(" ", ""))) continue;
    if (/^\*?\*?Symbol/i.test(cells[0])) continue;
    const names = symbolsInCell(cells[0]);
    if (names.length === 0) continue;
    const kindCell = cells.length >= 4 ? cells[1] : "";
    const roleCell = cells.length >= 4 ? cells[2] : cells[1];
    for (const name of names) {
      if (rows.has(name)) continue;
      const kind = /type/i.test(kindCell) && !/value/i.test(kindCell)
        ? "type"
        : /value/i.test(kindCell) && !/type/i.test(kindCell)
          ? "const"
          : name[0] === name[0].toUpperCase() && name[0] !== name[0].toLowerCase()
            ? "type"
            : "const";
      rows.set(name, { name, kind, summary: roleCell.replace(/\*\*/g, "").trim() || null, signature: null });
    }
  }
  return [...rows.values()].sort((a, b) => a.name.localeCompare(b.name));
}

// ─── lsp public-api + agent tools ────────────────────────────────────────────

function parseStringArrayConst(src, constName) {
  const m = new RegExp(String.raw`export const ${escRe(constName)} = \[([\s\S]*?)\] as const`).exec(src);
  if (!m) return [];
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

function parseAgentToolSources() {
  const src = read("packages/lsp/src/agent-tools.ts");
  const m = /export const AGENT_TOOL_SOURCES = \{([\s\S]*?)\} as const/.exec(src);
  if (!m) return [];
  const out = [];
  for (const row of m[1].matchAll(/(?:"([^"]+)"|([\w$]+))\s*:\s*"([^"]+)"/g)) {
    out.push({ key: row[1] || row[2], source: row[3] });
  }
  return out;
}

function buildAgentRows() {
  const tools = parseAgentToolSources();
  const pub = read("packages/lsp/src/public-api.ts");
  const agentNames = parseStringArrayConst(pub, "NUDO_AGENT_TOOL_NAMES");
  const slash = parseStringArrayConst(pub, "NUDO_SLASH_REQUESTS");
  const slashOf = (toolKey) => {
    const dotted = toolKey === "codeLens" ? null : `nudo.${toolKey}`;
    return slash.find((s) => dotted && s.replace("/", ".") === dotted) ?? null;
  };

  const rows = [];
  const seen = new Set();
  for (const t of tools) {
    seen.add(t.key);
    const isServerOnly = t.key === "codeLens";
    const cmd = isServerOnly ? "(server-only, no command)" : `nudo.${t.key}`;
    const alias = isServerOnly ? null : slashOf(t.key);
    rows.push({
      name: t.key,
      kind: "fn",
      summary: `${cmd}${alias ? ` / \`${alias}\`` : ""} — ${t.source}`,
      signature: isServerOnly ? null : alias ? `nudo.${t.key} | ${alias}` : `nudo.${t.key}`,
    });
  }
  // editor-only protocol names (not AGENT_TOOL_SOURCES) — listed for completeness
  for (const name of ["selectCase", "getActiveCases"]) {
    if (seen.has(name)) continue;
    const cmd = `nudo.${name}`;
    const alias = slash.find((s) => s.replace("/", ".") === cmd) ?? null;
    rows.push({
      name,
      kind: "fn",
      summary: `${cmd}${alias ? ` / \`${alias}\`` : ""} — editor command (not an agent tool)`,
      signature: alias ? `${cmd} | ${alias}` : cmd,
    });
  }
  // flag which keys are agent tools when the lists disagree
  for (const n of agentNames) {
    if (!seen.has(n)) {
      rows.push({ name: n, kind: "fn", summary: `nudo.${n} — agent tool name (public-api)`, signature: `nudo.${n}` });
    }
  }
  return rows.sort((a, b) => a.name.localeCompare(b.name));
}

function buildLspRows() {
  const rows = parseBarrel("packages/lsp/src/index.ts");
  // also surface the side-effect-free freeze constants package export
  const pub = parseBarrel("packages/lsp/src/public-api.ts");
  for (const r of pub) {
    if (!rows.some((x) => x.name === r.name)) rows.push(r);
  }
  rows.sort((a, b) => a.name.localeCompare(b.name));

  // protocol inventory rows from PUBLIC_API.md §3 (commands)
  const md = read("packages/lsp/PUBLIC_API.md");
  const start = md.indexOf("## 3. executeCommand");
  const stop = md.indexOf("## 4. Custom requests");
  const proto = [];
  if (start !== -1 && stop !== -1) {
    for (const line of md.slice(start, stop).split("\n")) {
      if (!line.trim().startsWith("|")) continue;
      const cells = line.split("|").slice(1, -1).map((c) => c.trim());
      if (cells.length < 2) continue;
      if (/^[-:]+$/.test(cells[0].replaceAll(" ", ""))) continue;
      const name = cells[0].replace(/`/g, "").trim();
      if (!name.startsWith("nudo.")) continue;
      proto.push({
        name,
        kind: "fn",
        summary: (cells[1] || "").replace(/\*\*/g, "") || null,
        signature: null,
      });
    }
  }
  return { exports: rows, commands: proto };
}

// ─── page builders ───────────────────────────────────────────────────────────

function buildCoreRows() {
  const rows = parseCorePublicApi();
  // Enrich from barrels: signatures/kinds when the name is a real export.
  const barrel = parseBarrel("packages/core/src/index.ts");
  const byName = new Map(barrel.map((r) => [r.name, r]));
  for (const r of rows) {
    const b = byName.get(r.name);
    if (!b) continue;
    if (!r.signature && b.signature) r.signature = b.signature;
    if (r.kind === "const" && b.kind === "fn") r.kind = "fn";
    if (r.kind === "const" && b.kind === "type") r.kind = "type";
    if (!r.summary && b.summary) r.summary = b.summary;
  }
  // Supplement with non-runtime index.ts names missing from §2 (skip $op runtime).
  for (const r of barrel) {
    if (r.name.startsWith("$")) continue;
    if (rows.some((x) => x.name === r.name)) continue;
    rows.push(r);
  }
  rows.sort((a, b) => a.name.localeCompare(b.name));
  return rows;
}

function buildBlock(lang, rows, extraNote) {
  const parts = [notice(lang)];
  if (extraNote) parts.push("", extraNote);
  parts.push("", symbolTable(lang, rows));
  return parts.join("\n");
}

