#!/usr/bin/env node
// 从 packages/*/CHANGELOG.md（changesets 生成）合成站点 Releases 页（en+zh），
// 并把 packages/*/package.json 的当前版本注入 guides/versioning.md 的版本表。
// 生成文件受标记块约束；CI 跑 `pnpm run docs:gen` 后 `git diff --exit-code`
// 即可拦截「改包号不改文档」的漂移。
//
// 运行：pnpm run docs:gen
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

const PKGS = [
  { dir: "core", name: "@nudojs/core" },
  { dir: "service", name: "@nudojs/service" },
  { dir: "nudojs", name: "nudojs (CLI)" },
  { dir: "parser", name: "@nudojs/parser" },
  { dir: "lsp", name: "@nudojs/lsp" },
  { dir: "env", name: "@nudojs/env" },
  { dir: "harvester", name: "@nudojs/harvester" },
  { dir: "vite-plugin", name: "vite-plugin-nudo" },
  { dir: "vscode", name: "nudo-vscode" },
];

const versionOf = (dir) =>
  JSON.parse(readFileSync(join(root, "packages", dir, "package.json"), "utf8")).version;

const changelogOf = (dir) => {
  const p = join(root, "packages", dir, "CHANGELOG.md");
  if (!existsSync(p)) return null;
  const src = readFileSync(p, "utf8");
  // 去掉文件自带 H1（页面自己生成结构），其余全量保留
  return src.replace(/^#[^\n]*\n+/, "").trimEnd() + "\n";
};

// ---------------- releases.md ----------------

const GEN_NOTICE_EN =
  "> Generated by `pnpm run docs:gen` from `packages/*/CHANGELOG.md` — do not edit. Breaking entries carry `**BREAKING**` and a one-line migration.";
const GEN_NOTICE_ZH =
  "> 由 `pnpm run docs:gen` 从 `packages/*/CHANGELOG.md` 生成 —— 请勿手改。破坏性条目带 `**BREAKING**` 与一行迁移说明。";

function buildReleases(lang) {
  const notice = lang === "zh" ? GEN_NOTICE_ZH : GEN_NOTICE_EN;
  const heading = lang === "zh" ? "发布记录" : "Releases";
  const pkgTable = lang === "zh"
    ? ["| 包 | 当前版本 |", "|----|----------|"]
    : ["| Package | Current version |", "|----------|-----------------|"];
  const parts = [
    "---",
    `description: ${
      lang === "zh"
        ? "各包发布记录 —— 由 changesets CHANGELOG 自动生成；破坏性变更含迁移说明。"
        : "Per-package release notes — generated from changesets CHANGELOGs; breaking changes carry migration notes."
    }`,
    `slug: /releases`,
    "---",
    "",
    `# ${heading}`,
    "",
    notice,
    "",
    ...pkgTable,
    ...PKGS.map((p) => `| \`${p.name}\` | ${versionOf(p.dir)} |`),
    "",
  ];
  for (const p of PKGS) {
    const cl = changelogOf(p.dir);
    parts.push(`## ${p.name} ${versionOf(p.dir)}`, "");
    if (cl) {
      parts.push(cl);
    } else {
      parts.push(
        lang === "zh"
          ? "_无 changesets CHANGELOG —— 以 GitHub Releases / 扩展市场发行说明为准。_"
          : "_No changesets CHANGELOG — see GitHub Releases / extension marketplace notes._",
        "",
      );
    }
  }
  return parts.join("\n");
}

writeFileSync(
  join(root, "packages/website/docs/releases.md"),
  buildReleases("en"),
);
writeFileSync(
  join(root, "packages/website/i18n/zh-Hans/docusaurus-plugin-content-docs/current/releases.md"),
  buildReleases("zh"),
);

// ---------------- versioning.md 版本表注入 ----------------

// 升级规则文案（编辑性内容，生成器持有，改这里而不是改页面）
const RULES_EN = {
  stable: "SemVer: breaking → major",
  lsp: "SemVer: breaking → major. Freeze inventory: `packages/lsp/PUBLIC_API.md`",
  env: "Minor may break; pin a minor for stable IDE/CI analysis. Handwritten env wins on overlapping modules/exports (`mergeHarvestUnderEnv`)",
  minor: "Minor may break",
  vscode: "Follow extension release notes; align bundled lsp before packaging (`packages/vscode/RELEASE_CHECKLIST.md`)",
};
const RULES_ZH = {
  stable: "SemVer：破坏性 → major",
  lsp: "SemVer：破坏性 → major。冻结清单：`packages/lsp/PUBLIC_API.md`",
  env: "minor 可能破坏；为 IDE/CI 分析稳定可锁 minor。手写 env 在重叠模块/导出上 wins（`mergeHarvestUnderEnv`）",
  minor: "minor 可能破坏",
  vscode: "以扩展发行说明为准；打包前对齐 bundled lsp 版本（见 `packages/vscode/RELEASE_CHECKLIST.md`）",
};

const lineOf = (v) => (parseInt(v, 10) === 0 ? "0.x" : `${parseInt(v, 10)}.x`);
const envVersions = `${versionOf("env")} / ${versionOf("harvester")}`;

function versionTable(lang) {
  const R = lang === "zh" ? RULES_ZH : RULES_EN;
  const head =
    lang === "zh"
      ? "| 包 | 版本线 | 升级规则 |\n|----|--------|----------|"
      : "| Package | Line | Upgrade rule |\n|---------|------|----------------|";
  const rows = [
    `| \`@nudojs/core\` | **${lineOf(versionOf("core"))}**（${versionOf("core")}） | ${R.stable} |`,
    `| \`@nudojs/service\` | **${lineOf(versionOf("service"))}**（${versionOf("service")}） | ${R.stable} |`,
    `| \`nudojs\` | **${lineOf(versionOf("nudojs"))}**（${versionOf("nudojs")}） | ${R.stable} |`,
    `| \`@nudojs/parser\` | **${lineOf(versionOf("parser"))}**（${versionOf("parser")}） | ${R.stable} |`,
    `| \`@nudojs/lsp\` | **${lineOf(versionOf("lsp"))}**（${versionOf("lsp")}） | ${R.lsp} |`,
    `| \`@nudojs/env\` / \`@nudojs/harvester\` | 0.x（${envVersions}） | ${R.env} |`,
    `| \`vite-plugin-nudo\` | 0.x（${versionOf("vite-plugin")}） | ${R.minor} |`,
    `| \`nudo-vscode\` | Marketplace | ${R.vscode} |`,
  ];
  return `${head}\n${rows.join("\n")}`;
}

const ECOSYSTEM_EN = `| Package | Current | Pin style | Notes |
|---------|---------|-----------|-------|
| \`@nudojs/env\` | ${versionOf("env")} (pre-1.0) | workspace / \`~0.4.0\` for bit-stable IDE/CI analysis | New Abs modules (e.g. \`events\` / \`stream\` / \`querystring\`) ship as **minor**; signature display may change. Handwritten env **wins** over harvest on overlapping modules/exports. |
| \`@nudojs/harvester\` | ${versionOf("harvester")} (pre-1.0) | workspace / \`~${versionOf("harvester")}\` | Harvest is a **side channel** — not the type-system source of truth. Budget defaults: \`maxFiles=12\`, \`maxMs=2500\`, disable via \`NUDO_HARVEST_NODE=off\`. |`;

const ECOSYSTEM_ZH = `| 包 | 当前 | 锁定方式 | 说明 |
|----|------|----------|------|
| \`@nudojs/env\` | ${versionOf("env")}（pre-1.0） | workspace / IDE·CI 稳定可锁 \`~0.4.0\` | 新 Abs 模块（如 \`events\` / \`stream\` / \`querystring\`）以 **minor** 发布；签名展示可能变化。手写 env 在重叠模块/导出上 **wins**。 |
| \`@nudojs/harvester\` | ${versionOf("harvester")}（pre-1.0） | workspace / \`~${versionOf("harvester")}\` | Harvest 是**旁路信道**，不是类型系统真理源。预算默认：\`maxFiles=12\`、\`maxMs=2500\`，\`NUDO_HARVEST_NODE=off\` 显式关闭。 |`;

function inject(path, begin, end, content) {
  const src = readFileSync(path, "utf8");
  const start = src.indexOf(begin);
  const stop = src.indexOf(end);
  if (start === -1 || stop === -1 || stop <= start) {
    throw new Error(`markers not found in ${path}`);
  }
  const next = `${src.slice(0, start)}${begin}\n${content}\n${src.slice(stop)}`;
  writeFileSync(path, next);
}

const EN_VERSIONING = join(root, "packages/website/docs/guides/versioning.md");
const ZH_VERSIONING = join(
  root,
  "packages/website/i18n/zh-Hans/docusaurus-plugin-content-docs/current/guides/versioning.md",
);
const B = "<!-- NUDO-VERSIONS:BEGIN -->";
const E = "<!-- NUDO-VERSIONS:END -->";

inject(EN_VERSIONING, B, E, versionTable("en"));
inject(ZH_VERSIONING, B, E, versionTable("zh"));
inject(
  EN_VERSIONING,
  "<!-- NUDO-ECOSYSTEM:BEGIN -->",
  "<!-- NUDO-ECOSYSTEM:END -->",
  ECOSYSTEM_EN,
);
inject(
  ZH_VERSIONING,
  "<!-- NUDO-ECOSYSTEM:BEGIN -->",
  "<!-- NUDO-ECOSYSTEM:END -->",
  ECOSYSTEM_ZH,
);

console.log("docs:gen wrote releases.md (en+zh) and refreshed versioning.md tables");
