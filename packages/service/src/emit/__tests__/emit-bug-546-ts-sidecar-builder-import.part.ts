/**
 * Bug 546：`nudo check --fix --write` 给 **`.ts` 源**写出的 `*.nudo.ts` 侧车
 * **不带 builder import** ⇒ 产物 **3× TS 错误**（TS2304 × 2 + TS2693）⇒
 * 过不了 `tsc --noEmit --strict`。
 *
 * 根因：quickfix 的侧车子句只写 DSL（`fn({ x: shape({ toFixed: any() }) })`），
 * 没按**侧车后缀**决定要不要补 builder import。`.nudo.ts` 是 TypeScript 文件：
 * `fn` / `shape` 没 import（TS2304），`any()` 撞 TS 类型关键字（TS2693）。
 *
 * 本钉：
 *   ① `.nudo.ts` 侧车带 builder import（TS 关键字构建器改名导入）
 *   ② 产物真的能过 `tsc --noEmit --strict`
 *   ③ `.nudo.js` 侧车维持「裸注入」纪律（不加 import）
 */
import { describe, it, expect } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { materializeAction } from "../quickfix-edits.ts";

const REPO_ROOT = join(import.meta.dirname, "..", "..", "..", "..", "..");
const TSC = join(REPO_ROOT, "node_modules", "typescript", "bin", "tsc");
const CORE_TYPES = join(REPO_ROOT, "packages", "core", "dist", "index.d.ts");

const SOURCE = `export function risky(x: any) {
  return x.toFixed();
}
`;

/** quickfix 物化出的侧车文本（`.ts` 源 ⇒ `*.nudo.ts` 侧车） */
function draftSidecar(sidecarPath: string): string {
  const plan = materializeAction({
    code: "nudo:entry-may-throw",
    fn: "risky",
    file: "/t/risky.ts",
    source: SOURCE,
    sidecarPath,
    action: { kind: "draft", label: "x" },
  });
  expect(plan?.sidecar?.newText, "draft quickfix 必须给出侧车文本").toBeDefined();
  return plan!.sidecar!.newText;
}

/** 产物真的过 `tsc --noEmit --strict` 吗 */
function tscNoEmit(fileName: string, text: string): { ok: boolean; out: string } {
  const dir = mkdtempSync(join(tmpdir(), "nudo-546-"));
  const file = join(dir, fileName);
  writeFileSync(file, text, "utf-8");
  writeFileSync(
    join(dir, "tsconfig.json"),
    JSON.stringify({
      compilerOptions: {
        strict: true,
        noEmit: true,
        skipLibCheck: true,
        target: "es2022",
        module: "esnext",
        moduleResolution: "bundler",
        paths: { "@nudojs/core": [CORE_TYPES] },
      },
      files: [fileName],
    }),
    "utf-8",
  );
  try {
    const out = execFileSync(process.execPath, [TSC, "--noEmit", "-p", join(dir, "tsconfig.json")], {
      encoding: "utf-8",
    });
    return { ok: true, out };
  } catch (e) {
    const err = e as { stdout?: string; stderr?: string };
    return { ok: false, out: `${err.stdout ?? ""}${err.stderr ?? ""}` };
  }
}

describe("Bug 546 — TS 侧车必须自带 builder import（产物过 tsc）", () => {
  it("`.nudo.ts` 侧车带 builder import，TS 关键字构建器改名导入", () => {
    const text = draftSidecar("/t/risky.nudo.ts");
    expect(text).toContain('import {');
    expect(text).toContain('from "@nudojs/core";');
    // `any` 是 TS 类型关键字 ⇒ 必须改名导入（`any as _nudo_any`）
    expect(text).toContain("any as _nudo_any");
    expect(text).toContain("_nudo_any()");
    // 不得出现裸的 TS 关键字构建器调用（TS2693）
    expect(text).not.toMatch(/(?<![\w$])any\s*\(/);
    expect(text).not.toMatch(/(?<![\w$])number\s*\(/);
    expect(text).not.toMatch(/(?<![\w$])string\s*\(/);
    expect(text).not.toMatch(/(?<![\w$])boolean\s*\(/);
  });

  it("产物真的过 `tsc --noEmit --strict`（改前 3× TS 错误）", () => {
    const text = draftSidecar("/t/risky.nudo.ts");
    const r = tscNoEmit("risky.nudo.ts", text);
    expect(r.ok, `tsc 失败：\n${r.out}`).toBe(true);
  });

  it("改前形态（无 import 的裸 DSL）确实过不了 tsc —— 回归有效性自证", () => {
    const bare = `// Generated by quickfix — review before accepting
export const risky = fn({ x: shape({ toFixed: any() }) });
`;
    const r = tscNoEmit("risky.nudo.ts", bare);
    expect(r.ok).toBe(false);
    expect(r.out).toContain("TS2304"); // Cannot find name 'fn' / 'shape'
    expect(r.out).toContain("TS2693"); // 'any' only refers to a type
  });

  it("负控制：`.nudo.js` 侧车维持「裸注入」纪律（不加 import）", () => {
    const text = draftSidecar("/t/risky.nudo.js");
    expect(text).not.toContain("import {");
    expect(text).toContain("fn(");
    expect(text).toContain("any()");
  });

  it("负控制：已有侧车自带 import 时不重复 import（沿用既有本地名）", () => {
    const existing = `import { fn, number } from "@nudojs/core";
export const other = fn({ x: number() });
`;
    const plan = materializeAction({
      code: "nudo:entry-may-throw",
      fn: "risky",
      file: "/t/risky.ts",
      source: SOURCE,
      sidecarPath: "/t/risky.nudo.ts",
      sidecarText: existing,
      action: { kind: "draft", label: "x" },
    });
    const text = plan!.sidecar!.newText;
    const importLines = text.split("\n").filter((l) => l.includes('from "@nudojs/core"'));
    // 既有 import 提供 `fn` ⇒ 新 import 只补缺失的构建器，不重复 import fn
    expect(importLines.length).toBe(2);
    expect(importLines[1]).not.toMatch(/(?<![\w$])fn(?![\w$])/);
    expect(importLines[1]).toContain("shape");
    expect(text).toContain("export const risky = fn(");
    // 追加 import 后的产物仍能编译
    const r = tscNoEmit("risky.nudo.ts", text);
    expect(r.ok, `tsc 失败：\n${r.out}`).toBe(true);
  });
});
