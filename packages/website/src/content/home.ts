export const contractCode = `import { number, fn, shape, string } from "@nudojs/core";

export const lineTotal = fn(
  { price: number().gt(0), qty: number().ge(1) },
  number().gt(0)
);

export const applyCoupon = fn(
  {
    order: shape({
      subtotal: number().ge(0),
      items: number().ge(0),
    }),
    code: string(),
  },
  shape({
    subtotal: number(),
    items: number(),
    total: number().ge(0),
    coupon: string(),
  })
);`;

