export const sourceCode = `export function lineTotal(price, qty) {
  return price * qty;
}

export function applyCoupon(order, code) {
  const rate =
    code === "VIP10" ? 0.1 :
    code === "VIP20" ? 0.2 : 0;
  return {
    ...order,
    total: order.subtotal * (1 - rate),
    coupon: rate > 0 ? code : null,
  };
}`;

