/**
 * BUG-029：`nudo:interface-drift` 对「同一域的**嵌套 union 拼写**」报假阳性
 * ⇒ `nudo health` exit 1 卡 CI。
 *
 * 平铺 `union(lit(1),lit(2),lit(3))` 经 `constraintToEntryAbs` 的
 * `samePrimLiteralUnionAbs` 快路径 = `prim number + or(eq…)`；
 * 嵌套 `union(union(lit(1),lit(2)),lit(3))` 走 joinAbs 回落 = `sum`、无顶层
 * pred ⇒ 双向 `leqAbs` 互不成立 ⇒ 同域假 drift。
 *
 * 本套件钉：同一调用域 {1,2,3} 下，两种拼写都**零** drift（比较前先规范化
 * union 成员，不比源码字符串）；且域真的不同时仍然报（不把规范化做成哑判）。
 */
import { describe, it, expect, beforeEach } from "vitest";
import { checkSource, pTrue } from "../index.ts";
import { resetCheckSourceMemo } from "../check.ts";
import { resetGeneralizeMemo } from "../generalize.ts";
import { takeInterfaceDiags } from "../interface.ts";
import { takeRefineDiags } from "../refine.ts";
import { makeFiles } from "./nudo-constraints.ts";

const SRC = `
export function pick(v) {
  return v;
}
pick(1);
pick(2);
pick(3);
`;

function driftOf(sidecar: string) {
  const { loadModule } = makeFiles({ "/t/lib.nudo.js": sidecar });
  const r = checkSource("/t/lib.js", SRC, pTrue, {
    loadModule,
    fromFile: "/t/lib.js",
  });
  return r.issues.filter((i) => i.code === "nudo:interface-drift");
}

// @generated 标记必须落在**该导出声明上方的注释块**里（生成段 = 该导出）
const HEAD = `import { fn, lit, union } from "@nudojs/core";
`;

describe("BUG-029 嵌套 union 拼写不得报假 drift", () => {
  beforeEach(() => {
    resetCheckSourceMemo();
    resetGeneralizeMemo();
    takeInterfaceDiags();
    takeRefineDiags();
  });

  it("平铺 union(lit(1),lit(2),lit(3)) → 零 drift", () => {
    expect(
      driftOf(`${HEAD}// @generated by nudo — do not edit
export const pick = fn({ v: union(lit(1), lit(2), lit(3)) });`),
    ).toEqual([]);
  });

  it("嵌套 union(union(lit(1),lit(2)), lit(3))（同一域）→ 零 drift", () => {
    expect(
      driftOf(`${HEAD}export const kinds = union(lit(1), lit(2));
// @generated by nudo — do not edit
export const pick = fn({ v: union(kinds, lit(3)) });`),
    ).toEqual([]);
  });

  it("域真的不同 → 仍报 drift（规范化不是哑判）", () => {
    const drifts = driftOf(`${HEAD}export const kinds = union(lit(1), lit(2));
// @generated by nudo — do not edit
export const pick = fn({ v: union(kinds, lit(4)) });`);
    expect(drifts).toHaveLength(1);
    expect(drifts[0]!.message).toContain("pick[v]");
  });
});
