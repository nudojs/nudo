/**
 * Bug 366 回归：`nudo:interface-drift` 必须吃**跨文件**的调用点证据。
 *
 * 机制（Bug 366）：drift 判定的「今日域」证据**只**来自 `checkSource` 评估
 * **被检查文件自身**时产生的 `AbsCallRecord` ⇒ 调用点在别的文件里时，
 * `--from` 写出的生成段**永远判不出陈旧**（落盘契约静默陈旧）。
 *
 * 修法：`CheckOptions.from`（可选字段 `from?: readonly AbsCallRecord[]`）
 * 把跨文件证据接进**同一条** drift 判定通道（check.ts / checkSourceInner）。
 */
import { describe, it, expect } from "vitest";
import { checkSource, pTrue } from "../index.ts";
import { $lit } from "../exec/runtime/state.ts";
import { abs } from "../abs.ts";
import type { AbsCallRecord } from "../ast-records.ts";

/** 被检查文件：源码已改成 number → string（与固化生成段不符） */
const LIB = `export function addOne(x) {
  return String(x) + "!";
}`;

/** 固化生成段（@generated 快照：x: lit(5) ⇒ lit(6)） */
const SIDECAR = [
  "// @generated by nudo - do not edit",
  "// source: lib.js:addOne",
  "export const addOne = fn({ x: lit(5) }, lit(6));",
].join("\n");

/** 跨文件调用点证据（`--from` 采集）：另一个文件里 addOne(5) */
const FROM_RECORD: AbsCallRecord = {
  fnName: "addOne",
  args: [$lit(5)],
  result: abs({ k: "prim", type: "string" }, undefined, undefined, "path"),
};

function opts(extra: Record<string, unknown> = {}) {
  return {
    loadModule: (spec: string) => (spec.endsWith(".nudo.js") ? SIDECAR : undefined),
    fromFile: "/t/lib.js",
    entryThrows: "off" as const,
    ...extra,
  };
}

function driftIssues(extra: Record<string, unknown> = {}) {
  return checkSource("/t/lib.js", LIB, pTrue, opts(extra)).issues.filter(
    (i) => i.code === "nudo:interface-drift",
  );
}

describe("Bug 366：drift 判定必须吃 --from 的跨文件调用点证据", () => {
  it("跨文件证据 ⇒ 报 nudo:interface-drift（修前 0 条）", () => {
    const issues = driftIssues({ from: [FROM_RECORD] });
    expect(issues.length).toBe(1);
    expect(issues[0]!.severity).toBe("warning");
    expect(issues[0]!.fn).toBe("addOne");
    expect(issues[0]!.message).toContain("addOne[return]");
  });

  it("控制组：没有跨文件证据 ⇒ 不报（无证据不判 drift）", () => {
    expect(driftIssues().length).toBe(0);
  });

  it("跨文件证据只报 1 条（参数位 lit(5) 未漂移 ⇒ 不报参数漂移）", () => {
    const issues = driftIssues({ from: [FROM_RECORD] });
    expect(issues.map((i) => i.message)).toEqual([
      "addOne[return]: persisted @generated segment ≠ today's inferred return",
    ]);
  });

  it("跨文件调用点在本文件内无位置 ⇒ 位置留空（不挂别的文件的行号）", () => {
    const issues = driftIssues({ from: [FROM_RECORD] });
    expect(issues[0]!.line).toBeUndefined();
  });

  it("跨文件证据不得凭空造出别的函数的漂移", () => {
    const other = driftIssues({
      from: [{ ...FROM_RECORD, fnName: "notHere" }],
    });
    expect(other.length).toBe(0);
  });
});
