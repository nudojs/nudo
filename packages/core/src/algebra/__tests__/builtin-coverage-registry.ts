/**
 * 宿主内建面覆盖地板·两级台账（配套 builtin-coverage-floor.test.ts）。
 *
 * 目的：防「未建模面静默漏网」——测试在运行时枚举 globalThis 自有名字 +
 * 策展 brand 的 `.prototype` / 构造器静态自有名字，任何未登记名字即失败。
 * 每条必须写清理由：
 * - `MODELED`：引擎有真实分发/校验 case（注释 cites 具体表/函数）；
 * - `ALLOWED_IMPRECISE`：有意不建模，接受 unknown 口径（写明原因）。
 * 拿不准的一律进 ALLOWED_IMPRECISE 并注明「未建模，接受 unknown」。
 *
 * 键形：
 * - `global:<Name>`            —— globalThis 自有属性名
 * - `<Brand>.static.<prop>`    —— 构造器/命名空间对象自有属性名
 * - `<Brand>.proto.<prop>`     —— `<Brand>.prototype` 自有属性名
 * - `Intl.ns.<prop>`           —— Intl 命名空间自有属性名（含子构造器名）
 * - `Intl.<Sub>.static/proto`  —— Intl 子构造器面
 *
 * 枚举口径：静态面跳过 `length/name/arguments/caller`（函数元属性，全宿主
 * 均匀未建模，不追踪）；原型面跳过 `constructor`（同因）。symbol 键自有
 * 属性（@@iterator 等）不进 getOwnPropertyNames，天然不在地板内。
 *
 * `VERSION_SKEW`：存在性随 Node 版本/执行上下文漂移的键（如 Temporal 仅
 * 新 Node、`module/require` 等仅 CJS 上下文）。这些键仍要求登记，但僵尸
 * 检查（运行时不存在 → 失败）对其豁免——缺席是版本差异而非台账腐化。
 */

