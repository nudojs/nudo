/**
 * ABS-12 R12-D：宿主能力清单（**default-deny**）。
 *
 * 分析即执行：生成码里的自由标识符会落到宿主全局。引擎已有两道路径保证
 * 「有副作用的名字不可执行」——env 注入 Abs 遮蔽同名全局 + 非 Abs 宿主值在
 * `$get/$call/$new` design fail-closed——但那是副产物，不是不变量：名单手写、
 * 新 Node 全局无人复核、`node:*` 模块无分类。
 *
 * 本清单把它们变成**显式策略**：
 * - `DENIED_HOST_GLOBALS`：有副作用 / 代码执行 / 跨上下文 / 持久存储的名字。
 *   运行期按**值身份**拦截（别名 `const f = fetch` 同样命中，见
 *   `exec/calls.ts::neverExecHostName`）；未列名默认 deny。
 * - `ALLOWED_HOST_GLOBALS`：显式复核过「按值暴露无副作用」或由 env 建模的名字。
 * - `HOST_GLOBAL_SNAPSHOT` / `NODE_BUILTIN_SNAPSHOT`：漂移门禁的快照——
 *   宿主新增名字必须先分类（默认-deny 保证未分类名字不可执行；门禁保证它
 *   不会静默留在快照外）。
 *
 * **诚实边界**：同 realm 的隐藏是防御纵深，不是安全边界；硬隔离需子进程/容器
 * （见 plan ABS-12 R12-B，另行拍板）。
 */
