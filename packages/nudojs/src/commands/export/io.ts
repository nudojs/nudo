/**
 * export — 写盘面：产物落盘（命名去重、覆盖策略、错误回放）。
 *
 * 写盘失败转 `nudo:path-io` 面（路径相对 cwd 展示，errno 原文不进 CI 日志），
 * 与 check/test 的路径错误面同构（message + fix: 提示 + exit 1）。
 *
 * 命名口径（Bug 609 / 622 / 623）：
 * - **产物名全局唯一**：同一 `--out` 目录里，两个模块不得落到同一路径。
 *   规范名（`<stem>.d.ts` / `<stem>.nudo.guard.ts` / `<fn>.nudo.standard.ts` …）
 *   优先；**目标已被别的模块占用**时改写「带模块键后缀」的名字
 *   （`<stem>.<key>.d.ts`），**绝不静默覆盖**。
 * - **模块键**（`ExportArtifacts.moduleKey`）：调用方给的模块稳定 id（源文件
 *   路径）。缺省时用**源文件 stem + 导出签名**兜底 —— 同一模块的两次导出
 *   口径相同 ⇒ 视为同一模块（可覆盖更新）；不同模块口径不同 ⇒ 产物名带键
 *   后缀（不覆盖）。
 * - **同名函数**（Bug 623）：standard 面每个函数一份文件 ⇒ 同名函数按序号
 *   派生（`C.m.nudo.standard.ts` / `C.m.2.nudo.standard.ts`），两份都在。
 *
 * 覆盖策略（Bug 617）：目标已存在且**不是本工具产物** ⇒ 拒绝覆盖（可诊断的
 * 路径错误面 + exit 1）；是本工具产物且**同一模块** ⇒ 覆盖更新；是本工具
 * 产物但**别的模块** ⇒ 换唯一名落盘（原文件保留）。
 *
 * 失败语义（Bug 616）：`--out` IO 失败转 `nudo:path-io` 面并 exit 1；**已写
 * 的文件不回滚**（产物是投影不是事务）⇒ 但**已落盘清单如实回放**（每行
 * `wrote <path>`），错误文案**点名失败的那个文件**。
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";
import { DIAG } from "@nudojs/core/internal";
import { displayPathOf, reportPathErrors, type PathError } from "../shared.ts";
import { schemaFileName, type SchemaDialectName } from "../../export-format.ts";

/** 待落盘的产物（各面拼好的文本块）。 */
export type ExportArtifacts = {
  /** 文件 stem（源文件名去扩展名） */
  stem: string;
  /** schema 方言（当前只有 zod） */
  dialect: SchemaDialectName;
  /** zod 模块源码（缺席 = 无 schema 产物） */
  schemaSource?: string;
  /** standard 面函数块（每块一份文件） */
  standardChunks: readonly string[];
  /** guard 面函数块（合成一份文件） */
  guardChunks: readonly string[];
  /** dts 面模块块（合成一份文件） */
  dtsChunks: readonly string[];
  /**
   * 模块标识（源文件的稳定 id，如相对路径）：产物名去重与「是不是同一个
   * 模块」的口径键。缺省时用**导出签名**兜底（见 {@link moduleTagOf}）。
   */
  moduleKey?: string;
};

/** 写盘结果：成功 ⇒ 落盘文件列表；失败 ⇒ 已上报路径错误面（exit 1）。 */
export type ExportWriteResult = {
  ok: boolean;
  written: string[];
};

/** 产物方言标签（命名去重口径；stdout 侧跨段改名同源）。 */
export type ArtifactDialect = "zod" | "standard" | "guard" | "dts";

/** 方言后缀（跨段 / 跨产物改名时的来源）。 */
export const DIALECT_SUFFIX: Record<ArtifactDialect, string> = {
  zod: "Zod",
  standard: "Standard",
  guard: "Guard",
  dts: "Dts",
};

/**
 * 流内唯一名：`<原名><方言后缀>`；仍占用则加数字后缀（`foo` → `fooStandard`
 * → `fooStandard2`）。
 *
 * 命名规则的**唯一产地**（stdout 侧跨方言段改名消费同一形状）。
 */
export function uniqueSegmentName(
  name: string,
  dialect: ArtifactDialect,
  used: Set<string>,
): string {
  const base = `${name}${DIALECT_SUFFIX[dialect]}`;
  if (!used.has(base)) return base;
  let i = 2;
  while (used.has(`${base}${i}`)) i++;
  return `${base}${i}`;
}

/** 一个待落盘产物（命名口径 + 内容）。 */
type ArtifactPlan = {
  /** 产物方言（签名抽取与诊断用） */
  kind: ArtifactDialect;
  /** 基名（模块 stem 或函数名） */
  base: string;
  /** 种类后缀（含扩展名） */
  suffix: string;
  /** 落盘内容（未加模块标记） */
  content: string;
};

/** 本工具产物的标记行（模块标识 + 「这份文件是 nudo 生成的」）。 */
const MODULE_MARKER = "// nudo-export-module:";

/** 本工具产物横幅（zod / standard 面自带；dts / guard 面由本模块补）。 */
const GENERATED_BANNER = "@generated by nudo export";

/** 短哈希（8 位十六进制）：模块键 → 文件名后缀。 */
function shortHash(text: string): string {
  return createHash("sha256").update(text).digest("hex").slice(0, 8);
}

/**
 * 产物里的**函数级**符号名（模块「导出签名」）。
 *
 * 只取函数级名字（不含 `<fn>_<param>` 这类参数级导出）⇒ 改参数名 / 改类型
 * 不改签名 ⇒ 同一模块的两次导出签名相同 ⇒ 可覆盖更新（不产生陈旧副本）。
 */
function signatureOf(kind: ArtifactDialect, content: string): string[] {
  const names = new Set<string>();
  if (kind === "standard" || kind === "guard") {
    // 段标题：`// === <fn> Standard Schema ===` / `// === <fn> Type Guards ===`
    for (const m of content.matchAll(/\/\/ === (\S+) (?:Standard Schema|Type Guards) ===/g)) {
      names.add(m[1]!);
    }
    return [...names].sort();
  }
  if (kind === "zod") {
    // `export const <fn>Input` / `export const <fn>Output` ⇒ 函数名
    for (const m of content.matchAll(/^export const ([A-Za-z_$][\w$]*?)(?:Input|Output)\b/gm)) {
      names.add(m[1]!);
    }
    return [...names].sort();
  }
  // dts 面：`export declare function <fn>` / `export declare class <fn>` / `export { … }`
  for (const m of content.matchAll(
    /^export\s+(?:declare\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm,
  )) {
    names.add(m[1]!);
  }
  for (const m of content.matchAll(/^export\s*\{([^}]*)\}/gm)) {
    for (const part of m[1]!.split(",")) {
      const n = part.trim().split(/\s+as\s+/).pop()?.trim();
      if (n) names.add(n);
    }
  }
  return [...names].sort();
}

/**
 * 模块标记值：调用方给的模块键优先；缺省用**源文件 stem + 导出签名**兜底。
 *
 * - **stem**：不同源文件 ⇒ 不同模块（standard 面按**函数名**命名时，同名函数
 *   的两个模块靠它区分 —— Bug 609）。
 * - **导出签名**：同 stem 的两个模块靠它区分（Bug 622）。
 *
 * 标记值写进产物首行 ⇒ 后续导出能判断「目标文件属于哪个模块」（同模块 ⇒
 * 覆盖更新；别的模块 ⇒ 换唯一名，不覆盖）。
 */
export function moduleTagOf(
  art: { kind: ArtifactDialect; content: string },
  moduleKey?: string,
  stem?: string,
): string {
  if (moduleKey !== undefined && moduleKey !== "") return moduleKey;
  const sig = signatureOf(art.kind, art.content);
  return `${stem ?? ""}|sig:${sig.join(",") || "(none)"}`;
}

/** 产物是否本工具生成（含 zod / standard 面自带横幅与本模块补的标记行）。 */
function isGeneratedByNudo(text: string): boolean {
  return text.includes(GENERATED_BANNER) || text.includes(MODULE_MARKER);
}

/** 产物里的模块标记值（无标记 ⇒ undefined）。 */
function moduleTagIn(text: string): string | undefined {
  const m = text.match(/^\/\/ nudo-export-module: (.+)$/m);
  return m?.[1];
}

/** 规范名 → 唯一名（模块键后缀插在基名与种类后缀之间）。 */
function uniqueName(base: string, suffix: string, tag: string): string {
  return `${base}.${shortHash(tag)}${suffix}`;
}

/** 批内规范名去重（同名函数：`C.m` → `C.m.2` → `C.m.3`）。 */
function uniqueBase(used: Set<string>, base: string, suffix: string): string {
  const canonical = `${base}${suffix}`;
  if (!used.has(canonical)) {
    used.add(canonical);
    return base;
  }
  let i = 2;
  while (used.has(`${base}.${i}${suffix}`)) i++;
  const out = `${base}.${i}`;
  used.add(`${out}${suffix}`);
  return out;
}

/** 产物计划：各面文本块 → 命名口径统一的待落盘项。 */
function planArtifacts(artifacts: ExportArtifacts): ArtifactPlan[] {
  const plan: ArtifactPlan[] = [];
  const used = new Set<string>();
  if (artifacts.schemaSource !== undefined) {
    const canonical = schemaFileName(artifacts.stem, artifacts.dialect);
    plan.push({
      kind: "zod",
      base: artifacts.stem,
      // 方言文件名口径的唯一产地是 export-format.ts ⇒ 后缀由规范名切出。
      suffix: canonical.slice(artifacts.stem.length),
      content: artifacts.schemaSource,
    });
  }
  if (artifacts.standardChunks.length > 0) {
    // 每函数一份模块（各自内联 __nudoCheck，避免合并文件时 helper 重复定义）
    for (const chunk of artifacts.standardChunks) {
      const m = chunk.match(/\/\/ === (\S+) Standard Schema ===/);
      const fnStem = m?.[1] ?? artifacts.stem;
      const header = `// @generated by nudo export --format standard — Standard Schema v1 (vendor: nudo)\n`;
      const body = chunk.startsWith("\n") ? chunk.slice(1) : chunk;
      plan.push({
        kind: "standard",
        base: uniqueBase(used, fnStem, ".nudo.standard.ts"),
        suffix: ".nudo.standard.ts",
        content: body.includes(GENERATED_BANNER) ? body + "\n" : header + body + "\n",
      });
    }
  }
  if (artifacts.guardChunks.length > 0) {
    plan.push({
      kind: "guard",
      base: artifacts.stem,
      suffix: ".nudo.guard.ts",
      content: artifacts.guardChunks.join("\n") + "\n",
    });
  }
  if (artifacts.dtsChunks.length > 0) {
    plan.push({
      kind: "dts",
      base: artifacts.stem,
      suffix: ".d.ts",
      content: artifacts.dtsChunks.join("\n") + "\n",
    });
  }
  return plan;
}

/** 目标路径决策：规范名优先；被别的模块占用 ⇒ 换唯一名；外来文件 ⇒ 拒绝。 */
function resolveTarget(
  outDir: string,
  art: ArtifactPlan,
  tag: string,
  content: string,
): { path: string } | { refuse: string } {
  const canonical = join(outDir, `${art.base}${art.suffix}`);
  if (!existsSync(canonical)) return { path: canonical };
  let existing: string;
  try {
    existing = readFileSync(canonical, "utf-8");
  } catch {
    return { path: canonical };
  }
  if (existing === content) return { path: canonical }; // 幂等重导：内容一致
  if (!isGeneratedByNudo(existing)) return { refuse: canonical }; // 手写产物：拒绝覆盖
  if (isSameModule(art, existing, tag)) return { path: canonical };
  // 别的模块占了规范名 ⇒ 换唯一名（带模块键后缀）；仍占用 ⇒ 加序号。
  let candidate = join(outDir, uniqueName(art.base, art.suffix, tag));
  let i = 2;
  while (existsSync(candidate)) {
    const body = safeRead(candidate);
    if (body === content) return { path: candidate };
    if (body !== undefined && !isGeneratedByNudo(body)) return { refuse: candidate };
    candidate = join(outDir, `${art.base}.${shortHash(tag)}.${i}${art.suffix}`);
    i++;
  }
  return { path: candidate };
}

/**
 * 「是不是同一个模块」：模块标记一致 ⇒ 是；标记缺失（旧版本产物）⇒ 按
 * **导出签名**判（签名一致 ⇒ 同一模块 ⇒ 可覆盖更新）。
 */
function isSameModule(art: ArtifactPlan, existingText: string, tag: string): boolean {
  const existingTag = moduleTagIn(existingText);
  if (existingTag !== undefined) return existingTag === tag;
  return (
    signatureOf(art.kind, existingText).join(",") === signatureOf(art.kind, art.content).join(",")
  );
}

/** 读文件（读不到 ⇒ undefined）。 */
function safeRead(path: string): string | undefined {
  try {
    return readFileSync(path, "utf-8");
  } catch {
    return undefined;
  }
}

/** 写盘失败诊断（`nudo:path-io` 面；提示指向**本命令**且可执行）。 */
function ioError(op: string, target: string, suggestion: string): PathError {
  return {
    path: target,
    code: DIAG.pathIo,
    message: `export --out ${op} failed: ${displayPathOf(target)}`,
    suggestion,
  };
}

/** mkdir 失败提示（可执行：指向本命令的 `--out`）。 */
const MKDIR_SUGGESTION =
  "export --out <dir>: the path must be a directory (or a path that can be created) — remove the file at that path, or pass a different --out directory";

/** write 失败提示（可执行：指向本命令的 `--out`）。 */
const WRITE_SUGGESTION =
  "export --out <file>: the target file must be writable — check the output directory permissions, or pass a different --out directory";

/** 拒绝覆盖外来文件提示（Bug 617）。 */
function refuseSuggestion(target: string): string {
  return `export --out <file>: nudo export does not overwrite files it did not generate — remove ${displayPathOf(target)}, or pass a different --out directory`;
}

/**
 * 产物落盘：mkdir → 逐面写文件 → 返回落盘清单（相对 cwd 的展示路径由调用方
 * 决定；此处返回绝对路径）。
 *
 * 失败语义（BUG-023 / Bug 616）：`--out` IO 失败转 `nudo:path-io` 面并
 * exit 1；**已写的文件不回滚**（产物是投影不是事务）⇒ 但**已落盘清单如实
 * 回放**（stdout 每行 `wrote <path>`），错误文案点名失败的那个文件。
 */
export function writeExportArtifacts(
  outDir: string,
  artifacts: ExportArtifacts,
): ExportWriteResult {
  const plan = planArtifacts(artifacts);
  try {
    mkdirSync(outDir, { recursive: true });
  } catch {
    reportPathErrors([ioError("mkdir", outDir, MKDIR_SUGGESTION)]);
    return { ok: false, written: [] };
  }
  const written: string[] = [];
  for (const art of plan) {
    const tag = moduleTagOf(art, artifacts.moduleKey, artifacts.stem);
    const content = `${MODULE_MARKER} ${tag}\n${art.content}`;
    const target = resolveTarget(outDir, art, tag, content);
    if ("refuse" in target) {
      reportPathErrors([
        {
          path: target.refuse,
          code: DIAG.pathIo,
          message: `export --out target exists and was not generated by nudo export: ${displayPathOf(target.refuse)}`,
          suggestion: refuseSuggestion(target.refuse),
        },
      ]);
      replayWritten(written);
      return { ok: false, written };
    }
    try {
      writeFileSync(target.path, content, "utf-8");
      written.push(target.path);
    } catch {
      reportPathErrors([ioError("write", target.path, WRITE_SUGGESTION)]);
      replayWritten(written);
      return { ok: false, written };
    }
  }
  return { ok: true, written };
}

/** 落盘清单的展示行（相对 cwd）。 */
export function writtenPathLines(written: readonly string[]): string[] {
  return written.map((p) => `wrote ${relative(process.cwd(), p)}`);
}

/**
 * 已落盘清单的回放（Bug 616）：写盘失败时把**已成功写入**的产物如实回放
 * （stdout 每行 `wrote <path>`）——「部分落盘」这一事实必须出现在输出里，
 * 不能只存在于磁盘。
 */
function replayWritten(written: readonly string[]): void {
  for (const line of writtenPathLines(written)) {
    console.log(line);
  }
}
