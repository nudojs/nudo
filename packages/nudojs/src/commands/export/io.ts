/**
 * export — 写盘面：产物落盘（路径、覆盖策略、原子写、错误回放）。
 *
 * 写盘失败转 `nudo:path-io` 面（路径相对 cwd 展示，errno 原文不进 CI 日志），
 * 与 check/test 的路径错误面同构（message + fix: 提示 + exit 1）。
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { DIAG } from "@nudojs/core/internal";
import { displayPathOf, reportPathErrors, type PathError } from "../shared.ts";
import { schemaFileName, type SchemaDialectName } from "../../export-format.ts";

/** 待落盘的产物（各面拼好的文本块）。 */
export type ExportArtifacts = {
  /** 文件 stem（源文件名去扩展名） */
  stem: string;
  /** schema 方言（当前只有 zod） */
  dialect: SchemaDialectName;
  /** zod 模块源码（缺席 = 无 schema 产物） */
  schemaSource?: string;
  /** standard 面函数块（每块一份文件） */
  standardChunks: readonly string[];
  /** guard 面函数块（合成一份文件） */
  guardChunks: readonly string[];
  /** dts 面模块块（合成一份文件） */
  dtsChunks: readonly string[];
};

/** 写盘结果：成功 ⇒ 落盘文件列表；失败 ⇒ 已上报路径错误面（exit 1）。 */
export type ExportWriteResult = {
  ok: boolean;
  written: string[];
};

/**
 * 产物落盘：mkdir → 逐面写文件 → 返回落盘清单（相对 cwd 的展示路径由调用方
 * 决定；此处返回绝对路径）。
 *
 * 失败语义（BUG-023）：`--out` IO 失败转 `nudo:path-io` 面并 exit 1；**已写
 * 的文件不回滚**（产物是投影不是事务）。
 */
export function writeExportArtifacts(
  outDir: string,
  artifacts: ExportArtifacts,
): ExportWriteResult {
  const ioError = (op: string): PathError => ({
    path: outDir,
    code: DIAG.pathIo,
    message: `export --out ${op} failed: ${displayPathOf(outDir)}`,
    suggestion: `check --out <dir> is writable and the path is a directory, then re-run nudo export`,
  });
  try {
    mkdirSync(outDir, { recursive: true });
  } catch {
    reportPathErrors([ioError("mkdir")]);
    return { ok: false, written: [] };
  }
  const written: string[] = [];
  try {
    if (artifacts.schemaSource !== undefined) {
      const p = join(outDir, schemaFileName(artifacts.stem, artifacts.dialect));
      writeFileSync(p, artifacts.schemaSource, "utf-8");
      written.push(p);
    }
    if (artifacts.standardChunks.length > 0) {
      // 每函数一份模块（各自内联 __nudoCheck，避免合并文件时 helper 重复定义）
      for (const chunk of artifacts.standardChunks) {
        const m = chunk.match(/\/\/ === (\S+) Standard Schema ===/);
        const fnStem = m?.[1] ?? artifacts.stem;
        const p = join(outDir, `${fnStem}.nudo.standard.ts`);
        const header = `// @generated by nudo export --format standard — Standard Schema v1 (vendor: nudo)\n`;
        const body = chunk.startsWith("\n") ? chunk.slice(1) : chunk;
        writeFileSync(p, body.includes("@generated") ? body + "\n" : header + body + "\n", "utf-8");
        written.push(p);
      }
    }
    if (artifacts.guardChunks.length > 0) {
      const p = join(outDir, `${artifacts.stem}.nudo.guard.ts`);
      writeFileSync(p, artifacts.guardChunks.join("\n") + "\n", "utf-8");
      written.push(p);
    }
    if (artifacts.dtsChunks.length > 0) {
      const p = join(outDir, `${artifacts.stem}.d.ts`);
      writeFileSync(p, artifacts.dtsChunks.join("\n") + "\n", "utf-8");
      written.push(p);
    }
  } catch {
    reportPathErrors([ioError("write")]);
    return { ok: false, written: [] };
  }
  return { ok: true, written };
}

/** 落盘清单的展示行（相对 cwd）。 */
export function writtenPathLines(written: readonly string[]): string[] {
  return written.map((p) => `wrote ${relative(process.cwd(), p)}`);
}
